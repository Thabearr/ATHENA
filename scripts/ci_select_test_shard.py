def _key(path) -> str:
    return PurePosixPath(str(path).replace("\\", "/")).as_posix()


def _weight(key: str, median: float) -> float:
    return DURATIONS.get(key, median)


def partition(files, count: int) -> list[list]:
    """Split ``files`` into ``count`` shards by LPT greedy; every file exactly once.

    Order: descending duration, ties by path. Each file goes to the least-loaded
    shard, ties by lowest index. Each shard is returned sorted by path.
    """
    if type(count) is not int or count < 1:
        raise ValueError("shard count must be a positive integer")
    items = list(files)
    keys = [_key(item) for item in items]
    if len(set(keys)) != len(keys):
        raise ValueError("duplicate test file in the shard input")
    median = statistics.median(DURATIONS.values()) if DURATIONS else 1.0
    order = sorted(range(len(items)), key=lambda i: (-_weight(keys[i], median), keys[i]))
    loads = [0.0] * count
    shards: list[list[int]] = [[] for _ in range(count)]
    for index in order:
        target = min(range(count), key=lambda shard: (loads[shard], shard))
        shards[target].append(index)
        loads[target] += _weight(keys[index], median)
    return [[items[i] for i in sorted(shard, key=lambda i: keys[i])] for shard in shards]


def predicted_loads(files, count: int) -> list[float]:
    """Predicted seconds per shard for ``partition(files, count)`` (reporting only)."""
    median = statistics.median(DURATIONS.values()) if DURATIONS else 1.0
    return [round(sum(_weight(_key(item), median) for item in shard), 1)
            for shard in partition(files, count)]


def select(files, number: int, count: int) -> list:
    """The files of shard ``number`` (1-based) after proving the partition is exact."""
    items = list(files)
    if type(number) is not int or not 1 <= number <= count:
        raise ValueError(f"shard number {number!r} is outside 1..{count!r}")
    shards = partition(items, count)
    if len(shards) != count:
        raise ValueError("balanced partition returned the wrong number of shards")
    assigned = [_key(item) for shard in shards for item in shard]
    if len(assigned) != len(set(assigned)) or sorted(assigned) != sorted(_key(item) for item in items):
        raise ValueError("balanced partition is not disjoint and complete")
    return shards[number - 1]
